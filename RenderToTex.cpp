	void RenderToTex::SaveD3DState()
	{
		_d3dState.ScissorRectsCount = _d3dState.ViewportsCount = D3D11_VIEWPORT_AND_SCISSORRECT_OBJECT_COUNT_PER_PIPELINE;
		_details._context->RSGetScissorRects(&_d3dState.ScissorRectsCount, _d3dState.ScissorRects);
		_details._context->RSGetViewports(&_d3dState.ViewportsCount, _d3dState.Viewports);
		_details._context->RSGetState(&_d3dState.RS);
		_details._context->OMGetBlendState(&_d3dState.BlendState, _d3dState.BlendFactor, &_d3dState.SampleMask);
		_details._context->OMGetDepthStencilState(&_d3dState.DepthStencilState, &_d3dState.StencilRef);
		_details._context->PSGetShaderResources(0, 1, &_d3dState.PSShaderResource);
		_details._context->PSGetSamplers(0, 1, &_d3dState.PSSampler);
		_d3dState.PSInstancesCount = _d3dState.VSInstancesCount = 256;
		_details._context->PSGetShader(&_d3dState.PS, _d3dState.PSInstances, &_d3dState.PSInstancesCount);
		_details._context->VSGetShader(&_d3dState.VS, _d3dState.VSInstances, &_d3dState.VSInstancesCount);
		_details._context->VSGetConstantBuffers(0, 1, &_d3dState.VSConstantBuffer);
		_details._context->IAGetPrimitiveTopology(&_d3dState.PrimitiveTopology);
		_details._context->IAGetIndexBuffer(&_d3dState.IndexBuffer, &_d3dState.IndexBufferFormat, &_d3dState.IndexBufferOffset);
		_details._context->IAGetVertexBuffers(0, 1, &_d3dState.VertexBuffer, &_d3dState.VertexBufferStride, &_d3dState.VertexBufferOffset);
		_details._context->IAGetInputLayout(&_d3dState.InputLayout);
		_details._context->OMGetRenderTargets(1, &_d3dState.RenderTargetView, &_d3dState.DepthStencilView);
	}
	//----------------------------------------------------------------------------

	void RenderToTex::RestoreD3DState()
	{
		// Restore modified DX state
		_details._context->RSSetScissorRects(_d3dState.ScissorRectsCount, _d3dState.ScissorRects);
		_details._context->RSSetViewports(_d3dState.ViewportsCount, _d3dState.Viewports);
		_details._context->RSSetState(_d3dState.RS);
		if (_d3dState.RS)
			_d3dState.RS->Release();
		_details._context->OMSetBlendState(_d3dState.BlendState, _d3dState.BlendFactor, _d3dState.SampleMask);
		if (_d3dState.BlendState)
			_d3dState.BlendState->Release();
		_details._context->OMSetDepthStencilState(_d3dState.DepthStencilState, _d3dState.StencilRef);
		if (_d3dState.DepthStencilState)
			_d3dState.DepthStencilState->Release();
		_details._context->PSSetShaderResources(0, 1, &_d3dState.PSShaderResource);
		if (_d3dState.PSShaderResource)
			_d3dState.PSShaderResource->Release();
		_details._context->PSSetSamplers(0, 1, &_d3dState.PSSampler);
		if (_d3dState.PSSampler)
			_d3dState.PSSampler->Release();
		_details._context->PSSetShader(_d3dState.PS, _d3dState.PSInstances, _d3dState.PSInstancesCount);
		if (_d3dState.PS)
			_d3dState.PS->Release();
		for (UINT i = 0; i < _d3dState.PSInstancesCount; i++)
			if (_d3dState.PSInstances[i])
				_d3dState.PSInstances[i]->Release();
		_details._context->VSSetShader(_d3dState.VS, _d3dState.VSInstances, _d3dState.VSInstancesCount);
		if (_d3dState.VS)
			_d3dState.VS->Release();
		_details._context->VSSetConstantBuffers(0, 1, &_d3dState.VSConstantBuffer);
		if (_d3dState.VSConstantBuffer)
			_d3dState.VSConstantBuffer->Release();
		for (UINT i = 0; i < _d3dState.VSInstancesCount; i++)
			if (_d3dState.VSInstances[i])
				_d3dState.VSInstances[i]->Release();
		_details._context->IASetPrimitiveTopology(_d3dState.PrimitiveTopology);
		_details._context->IASetIndexBuffer(_d3dState.IndexBuffer, _d3dState.IndexBufferFormat, _d3dState.IndexBufferOffset);
		if (_d3dState.IndexBuffer)
			_d3dState.IndexBuffer->Release();
		_details._context->IASetVertexBuffers(0, 1, &_d3dState.VertexBuffer, &_d3dState.VertexBufferStride, &_d3dState.VertexBufferOffset);
		if (_d3dState.VertexBuffer)
			_d3dState.VertexBuffer->Release();
		_details._context->IASetInputLayout(_d3dState.InputLayout);
		if (_d3dState.InputLayout)
			_d3dState.InputLayout->Release();
		_details._context->OMSetRenderTargets(1, &_d3dState.RenderTargetView, _d3dState.DepthStencilView);
		if (_d3dState.RenderTargetView)
			_d3dState.RenderTargetView->Release();
		if (_d3dState.DepthStencilView)
			_d3dState.DepthStencilView->Release();
	}
